def fmt(raw, nd):
    return ins._fmt_csv(raw, nd, comma=(nd == 0 and abs(float(raw)) >= 1000))


class Table(object):
    def __init__(self, k, kraw):
        self.k, self.kraw, self.rows = k, kraw, []

    def add(self, label, id_, nd=1, unit="", caveat="", null=None, n_field="n_machines", n_nd=0, lo_nd=None, hi_nd=None, show_n=True):
        r = self.k.loc[id_]
        raw = self.kraw.loc[id_]
        val = fmt(raw["value"], nd) + unit
        interval = ""
        flag = ""
        if not pd.isna(r.interval_low):
            interval = "[%s to %s]" % (fmt(raw["interval_low"], lo_nd if lo_nd is not None else nd), fmt(raw["interval_high"], hi_nd if hi_nd is not None else nd))
            if null is not None and float(fmt(raw["interval_low"], nd)) <= null:
                flag = " **Interval touches or includes %g.**" % null
        n = ""
        if show_n and not pd.isna(r[n_field]):
            n = fmt(raw[n_field], n_nd)
        self.rows.append((label, val, interval, n, "`%s`" % id_, (caveat + flag).strip()))

    def md(self):
        lines = ["| Label | Value | 95% interval | n machines | key_numbers id | Caveat |", "|---|---|---|---|---|---|"]
        for r in self.rows:
            lines.append("| " + " | ".join(r) + " |")
        return "\n".join(lines)


